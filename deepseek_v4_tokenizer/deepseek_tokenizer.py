import transformers

chat_tokenizer_dir = "./"

tokenizer = transformers.AutoTokenizer.from_pretrained( 
        chat_tokenizer_dir, trust_remote_code=True
        )

result = tokenizer.encode("我这句话花了几毛钱")

print("token ids:", result)
print("token 数量:", len(result))
